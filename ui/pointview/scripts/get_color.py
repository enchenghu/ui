str_list = ["static const std::uint_t r[] = {", "static const std::uint_t g[] = {", "static const std::uint_t b[] = {"]

for c in rgb_value:
    for i in range(3):
        str_list[i] = str_list[i] + str(int(255 * c[i])) + ","

for i in range(3):
    str_list[i] = str_list[i] + "};"
    print(str_list[i])

fig = plt.figure()
ax = fig.add_axes(np.linspace(0, 1, 4))

cb = mpl.colorbar.ColorbarBase(ax, orientation='horizontal',
                               cmap=map_name)

plt.savefig(map_name + '.png', bbox_inches='tight')

