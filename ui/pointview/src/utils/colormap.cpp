Colormap::Colormap() {
  for (int i = 0; i < 256; i++) {
    r_.push_back(255);
    g_.push_back(255);
    b_.push_back(255);
    rgba_.push_back(0xffffffff);
  }
}

bool Colormap::setType(const std::string& type) {
  if (type == "jet") {
    using namespace jet;
    initColormap(r, g, b);
  } else if (type == "bwr") {
    using namespace bwr;
    initColormap(r, g, b);
  } else if (type == "plasma") {
    using namespace plasma;
    initColormap(r, g, b);
  } else if (type == "rainbow") {
    using namespace rainbow;
    initColormap(r, g, b);
  } else if (type == "gray") {
    for (int i = 0; i < 256; i++) {
      r_[i] = i;
      g_[i] = i;
      b_[i] = i;
    }
  } else if (type == "AutoxMaxRange") {
    using namespace autoxmaxrange;
    initColormap(r, g, b);
    range_min_ = 0;
    range_max_ = 255;
  } else {
    // do nothong
    return false;
  }

  // update rgba_
  for (int i = 0; i < 256; i++) {
    rgba_[i] = (r_[i] << 24) | (g_[i] << 16) | (b_[i] << 8) | 0xff;
  }
  return true;
}
void Colormap::setRange(double min, double max) {
  assert(min < max);
  range_min_ = min;
  range_max_ = max;
}
void Colormap::setRangeMin(double min) {
  assert(min < range_max_);
  range_min_ = min;
}
void Colormap::setRangeMax(double max) {
  assert(range_min_ < max);
  range_max_ = max;
}

void Colormap::get(double v, uint8_t& r, uint8_t& g, uint8_t& b) {
  v = (v - range_min_) / (range_max_ - range_min_) * 255;
  auto idx = static_cast<int>(v);
  idx = getGammaV(static_cast<uint8_t>(std::clamp(idx, 0, 255)));
  r = r_[idx];
  g = g_[idx];
  b = b_[idx];
}

uint32_t Colormap::get(double v) {
  v = (v - range_min_) / (range_max_ - range_min_) * 255;
  auto idx = static_cast<int>(v);
  idx = getGammaV(static_cast<uint8_t>(std::clamp(idx, 0, 255)));
  return rgba_[idx];
}

void Colormap::initColormap(const std::uint8_t* r, const std::uint8_t* g,
                            const std::uint8_t* b) {
  for (int i = 0; i < 256; i++) {
    r_[i] = r[i];
    g_[i] = g[i];
    b_[i] = b[i];
  }
}

bool Colormap::readGammaFile(std::string filename) {
  gamma_v_.clear();
  std::ifstream csv_data(filename, std::ios::in);
  std::string line;
  if (!csv_data.is_open()) {
    LOG(ERROR) << "Error! open failed: " << filename << std::endl;
    return false;
  }
  gamma_v_.push_back(0);
  while (std::getline(csv_data, line)) {
    uint8_t num = static_cast<uint8_t>(std::atoi(line.c_str()));
    gamma_v_.push_back(num);
  }
  if (gamma_v_.size() != 256) {
    LOG(ERROR) << "Error! gamma_v_ size is " << gamma_v_.size() << std::endl;
    return false;
  }
  csv_data.close();
  return true;
}

uint8_t Colormap::getGammaV(uint8_t idx) {
  if (gamma_v_.size() > idx && use_gamma_)
    return gamma_v_.at(idx);
  else
    return idx;
}

